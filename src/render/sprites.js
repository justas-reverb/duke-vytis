/**
 * One pose as a grid of colours (or null), ready to rasterise.
 *
 * `squash` compresses vertically and keeps the FEET on the bottom row, because the feet
 * are the edge the game positions him by. Squashing about the centre would float him.
 */
function poseGrid(name, facing) {
  const p = POSE[name];
  // Assembled rather than copied: see assembleHeld. Built once, facing right, and
  // MIRRORED for the left -- running the assembly again on a mirrored drawing would
  // round its pull direction the other way and give the two facings different bodies.
  if (p.hold) {
    const g = HELD.grid;
    return facing === 'left' ? g.map((r) => r.slice().reverse()) : g.map((r) => r.slice());
  }
  // `mirror` flips the DRAWING; `facing` flips the whole pose for movement. Work out
  // which it is up front, because the SOURCE has to change with it: a flipped pose reads
  // from the copy whose heraldry was mirrored in advance, so the flip cancels out.
  const flip = (facing === 'left') !== !!p.mirror;
  const src = ART[p.art];

  const out = Array.from({ length: SPR_H }, () => new Array(SPR_W).fill(null));
  const k = p.squash || 1;
  const destH = Math.max(1, Math.round(SPR_H * k));
  const top = SPR_H - destH;
  const bob = p.bob || 0;

  for (let y = 0; y < destH; y++) {
    const sy = Math.min(SPR_H - 1, Math.floor(y / k));
    const row = src[sy] || '';
    const dy = y + top + bob;
    if (dy < 0 || dy >= SPR_H) continue;
    for (let x = 0; x < SPR_W; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      // A key with no colour is loud rather than invisible: an unmapped character is a
      // typo in generated data and should be impossible to miss.
      out[dy][flip ? SPR_W - 1 - x : x] = INKS[ch] || '#ff00ff';
    }
  }
  return out;
}

// --- colour by ROLE, never by palette letter -----------------------------------
//
// The palette is regenerated whenever the sheet is re-imported and its letters move
// with it: 'D' was a steel grey on one import and is a mid grey on this one. Anything
// that has to find "the gold" or "the blue" asks for a hue, the way gemsFor below
// already does, so a re-import cannot quietly turn his armour pink.
function tone(col) {
  const n = parseInt(col.slice(1), 16);
  const r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn;
  let h = 0;
  if (d) {
    if (mx === r) h = 60 * (((g - b) / d) % 6);
    else if (mx === g) h = 60 * ((b - r) / d + 2);
    else h = 60 * ((r - g) / d + 4);
  }
  if (h < 0) h += 360;
  return { h, s: mx ? d / mx : 0, v: mx };
}
const ROLE_TEST = {
  // Gold: the crown, the cross, the rims. The same test the crown glint uses.
  gold: (c) => { const t = tone(c); return t.v >= 110 && t.s > 0.35 && t.h >= 28 && t.h <= 58; },
  // The tabard. Navy through azure.
  blue: (c) => { const t = tone(c); return t.s > 0.3 && t.h >= 200 && t.h <= 250 && t.v >= 50; },
  // The shield's field. His beard is the same family of reds, so a red has to be
  // saturated AND nearer crimson than auburn -- see "A shield found by its colour".
  red: (c) => { const t = tone(c); return t.s >= 0.5 && t.v >= 60 && (t.h <= 12 || t.h >= 345); },
  // Hair, beard and skin: the warm browns and tans that are not gold.
  warm: (c) => { const t = tone(c); return t.s >= 0.35 && t.h > 12 && t.h < 32 && t.v >= 70; },
  // Plate: unsaturated, neither the black outline nor the white specular.
  steel: (c) => { const t = tone(c); return t.s < 0.12 && t.v >= 70 && t.v <= 215; },
};
function shareOf(grid, cells, test) {
  let k = 0;
  for (const [x, y] of cells) if (test(grid[y][x])) k++;
  return cells.length ? k / cells.length : 0;
}

/** Every 8-connected piece of a drawing, biggest first, with its cells and box. */
function components(grid) {
  const seen = grid.map((r) => r.map(() => false));
  const out = [];
  for (let y = 0; y < SPR_H; y++) {
    for (let x = 0; x < SPR_W; x++) {
      if (!grid[y][x] || seen[y][x]) continue;
      const stack = [[x, y]];
      seen[y][x] = true;
      const cells = [];
      let x0 = x, y0 = y, x1 = x, y1 = y, sx = 0, sy = 0;
      while (stack.length) {
        const [cx, cy] = stack.pop();
        cells.push([cx, cy]);
        sx += cx; sy += cy;
        if (cx < x0) x0 = cx; if (cx > x1) x1 = cx;
        if (cy < y0) y0 = cy; if (cy > y1) y1 = cy;
        for (let dy = -1; dy <= 1; dy++) {
          for (let dx = -1; dx <= 1; dx++) {
            const nx = cx + dx, ny = cy + dy;
            if (nx < 0 || ny < 0 || nx >= SPR_W || ny >= SPR_H) continue;
            if (!grid[ny][nx] || seen[ny][nx]) continue;
            seen[ny][nx] = true;
            stack.push([nx, ny]);
          }
        }
      }
      out.push({ cells, n: cells.length, x0, y0, x1, y1,
        cx: sx / cells.length, cy: sy / cells.length });
    }
  }
  return out.sort((a, b) => b.n - a.n);
}

// Anything smaller than this is a stray resample pixel, not a piece of him. The same
// floor splitBits uses.
const MIN_PIECE = 24;
// How far a pulled-in piece is pushed INTO him past first contact: this fraction of its
// own narrower side, and never less than two art pixels. A fixed two pixels was tried
// first and read wrong at any angle but one -- a shield fifty pixels wide touching his
// sleeve at a single point hangs off him like a flag. A fifth of its width puts it
// against his forearm, which is what held means.
const HOLD_BITE = 0.18;
// The crown is walked further down, onto the head rather than the top of the hair: eight
// art pixels, about a fifth of its height. And where it lands on him, its DARK pixels give
// way to his -- the drawing shows the crown in the air from below, so its lower rows are
// the inside of the band, and painted over his hair that dark slot read as a gap between
// his head and his crown at every tumble but the upright one.
const CROWN_SEAT = 8;
const CROWN_DARK = 70;   // tone value (0-255) below which a crown pixel is its inside

/**
 * Put the plunge back together: cell 14 with everything that is flying off him moved
 * back onto him, plus where his parts are on that body.
 *
 * The drawing is a body and a handful of loose pieces -- a crown in the air above his
 * head, a shield and a sword falling away below. The body is the largest piece; each
 * loose one is walked toward it a pixel at a time until it touches, then HOLD_BITE of
 * its own width further, so it overlaps rather than abuts. The crown is walked straight DOWN, onto
 * the head it came off; everything else toward the body's centre, which lands the
 * shield on his forearm and the sword against his side. Strays under MIN_PIECE are left
 * where they were drawn.
 *
 * Found by shape and colour, never by coordinates, because the sheet is re-imported
 * and every coordinate in it moves when it is.
 *
 * The anchors are where each KIND of piece sits on this body, in its own art pixels --
 * so the splat can throw the head from where his head was and not from a clump in the
 * middle of him. See SPLAT_BITS.
 */
function assembleHeld(src) {
  const out = src.map((r) => r.slice());
  const comps = components(src);
  if (!comps.length) return { grid: out, anchors: {}, crown: null };
  const body = comps[0];
  const solid = new Uint8Array(SPR_W * SPR_H);
  for (const [x, y] of body.cells) solid[y * SPR_W + x] = 1;

  const loose = comps.slice(1).filter((c) => c.n >= MIN_PIECE);
  for (const c of loose) for (const [x, y] of c.cells) out[y][x] = null;

  // Which loose piece is which. The crown is the goldest; the shield the reddest.
  let crown = null, shield = null;
  for (const c of loose) {
    c.gold = shareOf(src, c.cells, ROLE_TEST.gold);
    c.red = shareOf(src, c.cells, ROLE_TEST.red);
    if (c.gold > 0.3 && (!crown || c.gold > crown.gold)) crown = c;
  }
  for (const c of loose) {
    if (c !== crown && c.red > 0.08 && (!shield || c.red > shield.red)) shield = c;
  }
  const sword = loose.find((c) => c !== crown && c !== shield) || null;

  const touches = (cells, dx, dy) => {
    for (const [x, y] of cells) {
      const px = x + dx, py = y + dy;
      for (let j = -1; j <= 1; j++) {
        for (let i = -1; i <= 1; i++) {
          const nx = px + i, ny = py + j;
          if (nx >= 0 && ny >= 0 && nx < SPR_W && ny < SPR_H && solid[ny * SPR_W + nx]) return true;
        }
      }
    }
    return false;
  };
  // Crown first, so the rest are pulled onto a body that is already wearing it.
  const order = [crown, ...loose.filter((c) => c !== crown)].filter(Boolean);
  for (const c of order) {
    let ux = 0, uy = 1;
    if (c !== crown) {
      const vx = body.cx - c.cx, vy = body.cy - c.cy;
      const len = Math.hypot(vx, vy) || 1;
      ux = vx / len; uy = vy / len;
    }
    let dx = 0, dy = 0;
    for (let t = 0; t < SPR_W + SPR_H; t++) {
      const tx = Math.round(ux * t), ty = Math.round(uy * t);
      if (touches(c.cells, tx, ty)) {
        const bite = Math.max(2, Math.round(HOLD_BITE * Math.min(c.x1 - c.x0 + 1, c.y1 - c.y0 + 1)));
        const k = t + (c === crown ? CROWN_SEAT : bite);
        dx = Math.round(ux * k); dy = Math.round(uy * k);
        break;
      }
    }
    c.dx = dx; c.dy = dy;
    for (const [x, y] of c.cells) {
      const nx = x + dx, ny = y + dy;
      if (nx < 0 || ny < 0 || nx >= SPR_W || ny >= SPR_H) continue;
      if (c === crown && solid[ny * SPR_W + nx] && tone(src[y][x]).v < CROWN_DARK) continue;
      out[ny][nx] = src[y][x];
      solid[ny * SPR_W + nx] = 1;
    }
  }

  // Back on the bottom row. Every pose stands on its cell's last row (test-sprites
  // fails any that does not), and pulling the sword up off it lifted the whole figure.
  let low = -1;
  for (let y = SPR_H - 1; y >= 0 && low < 0; y--) if (out[y].some(Boolean)) low = y;
  const shift = low < 0 ? 0 : SPR_H - 1 - low;
  const grid = shift
    ? out.map((_, y) => (y - shift >= 0 ? out[y - shift] : new Array(SPR_W).fill(null)))
    : out;

  // Where his parts are, in the assembled drawing's own pixels (y down).
  const at = (c) => (c ? { ax: c.cx + c.dx, ay: c.cy + c.dy + shift } : null);
  const bw = body.x1 - body.x0 + 1, bh = body.y1 - body.y0 + 1;
  let torso = { ax: body.cx, ay: body.cy + shift };
  {
    let n = 0, sx = 0, sy = 0;
    for (const [x, y] of body.cells) if (ROLE_TEST.blue(src[y][x])) { n++; sx += x; sy += y; }
    if (n > 20) torso = { ax: sx / n, ay: sy / n + shift };
  }
  let head = { ax: torso.ax, ay: torso.ay - bh * 0.3 };
  if (crown) {
    // The head is whatever of him is directly under the seated crown.
    const cx0 = crown.x0 + crown.dx, cx1 = crown.x1 + crown.dx;
    const top = crown.y1 + crown.dy + 1, bottom = top + (cx1 - cx0);
    let n = 0, sx = 0, sy = 0;
    for (const [x, y] of body.cells) {
      if (x >= cx0 && x <= cx1 && y >= top && y <= bottom) { n++; sx += x; sy += y; }
    }
    if (n > 20) head = { ax: sx / n, ay: sy / n + shift };
  }
  const anchors = {
    head,
    torso,
    crown: at(crown) || { ax: head.ax, ay: head.ay - bh * 0.15 },
    shield: at(shield) || { ax: torso.ax - bw * 0.3, ay: torso.ay },
    sword: at(sword) || { ax: torso.ax + bw * 0.3, ay: torso.ay },
    // Limbs are not separable in the plunge drawing, so they go where limbs go: arms
    // out to his sides a little above the tabard's centre, legs close in below it.
    arm: (k) => ({ ax: torso.ax + (k % 2 ? 1 : -1) * bw * (0.3 + 0.06 * (k >> 1)),
      ay: torso.ay - bh * (0.12 - 0.08 * (k >> 1)) }),
    leg: (k) => ({ ax: torso.ax + (k % 2 ? 1 : -1) * bw * 0.1, ay: torso.ay + bh * 0.3 }),
  };
  return { grid, anchors, crown: crown ? { ...crown, dy: crown.dy + shift } : null, src };
}

