/**
 * How far below its centre the lowest point of a w x h piece turned by `rot` is, and
 * how far to either side its widest point reaches. World units.
 *
 * CONTINUOUS in the angle, although the piece is only ever DRAWN at quarter turns. At a
 * quarter turn the two agree exactly, which is every moment it touches the floor: its
 * spin is planned to put it on a quarter turn at every strike (see Game.planGib). In
 * between, the true extent is never smaller than the drawn one, so a piece turning
 * near the floor is lifted by it rather than drawn sunk into it.
 */
export function halfHeight(w, h, rot) {
  return (Math.abs(Math.cos(rot)) * h + Math.abs(Math.sin(rot)) * w) / 2;
}
export function halfWidth(w, h, rot) {
  return (Math.abs(Math.cos(rot)) * w + Math.abs(Math.sin(rot)) * h) / 2;
}

/**
 * The rectangle a piece is DRAWN in: its quarter turn, and the box snapped to the art
 * grid by its corner rather than its centre.
 *
 * By the corner because a piece an odd number of art pixels across has its centre half
 * a pixel off the grid, and snapping the centre then puts every edge between two pixels
 * -- a resample. Resting, `bottom` is exactly the contact line. The renderer draws with
 * this and test-death.mjs checks it; neither has its own copy.
 */
export function pieceBox(w, h, x, y, rot) {
  const q = ((Math.round(rot / (Math.PI / 2)) % 4) + 4) % 4;
  const W = q % 2 ? h : w, H = q % 2 ? w : h;
  const left = Math.round((x - W / 2) * PX) / PX;
  const bottom = Math.round((y - H / 2) * PX) / PX;
  return { q, W, H, left, bottom };
}

/**
 * Where art pixel (ax, ay) of `frame` is in the world, relative to the point the pose
 * is drawn at -- exactly as drawSprite draws it: mirrored for `flip`, turned `q` quarter
 * turns about the cell's centre, the cell's bottom FOOT_DROP below that point.
 *
 * The one place that transform is written down for anything other than the blit. The
 * splat throws each piece from where it WAS in the last frame drawn, and a second copy
 * of this arithmetic is how a body bursts from a point beside itself.
 */
export function posePoint(frame, ax, ay, flip = false, q = 0) {
  // (ax, ay) index a pixel, so its centre is half a pixel in.
  let lx = (ax + 0.5) / PX - BODY_W / 2;   // from the cell's centre, world units, x right
  const ly = (ay + 0.5) / PX - BODY_H / 2; // ...and y DOWN, the canvas's frame inside drawSprite
  if (flip && !FRONT_FRAMES.has(frame)) lx = -lx;
  const k = ((Math.round(q) % 4) + 4) % 4;
  const c = [1, 0, -1, 0][k], s = [0, 1, 0, -1][k];
  const rx = lx * c - ly * s, ry = lx * s + ly * c;
  return { x: rx, y: BODY_H / 2 - (FOOT_DROP[frame] || 0) - ry };
}

// --- the crown's gems, found rather than typed, PER POSE -----------------------
//
// The renderer puts a travelling glint on a gem, which means it needs to know where the
// gems are. In the hand-authored sprite those were eight hand-counted column numbers that
// had to be re-measured every time the crown moved a pixel.
//
// They were then measured once, off idle0, and used for every pose -- which is why the
// glint was reported floating off his head. His crown is in a different place in every
// drawing: running he is pitched forward, landing he is crouched, tucked he is upside
// down. One measurement cannot describe all of them, and the one it does describe
// is the pose you spend the least time in.
//
// So every pose is measured on its own, on THAT drawing's own pixels: the topmost row
// with a real run of GOLD in it, which is the crown (see the test inside gemsFor).
//
// It was two other things first. Blueness: an older sheet set small blue stones in the
// crown and this hunted for them; the crown now is gold with lit points, so the blue test
// found nothing, fell through to its fallback and returned a single gem at the centre of
// the sprite. One gem is not a travelling glint, it is a stuck one. Then brightness, the
// brightest pixels in the top third of the ink, which lost to gold for the reasons given
// inside gemsFor.
function gemsFor(name) {
  const grid = FRAMES[name];
  const mid = Math.round(SPR_W / 2);
  if (!grid) return { cols: [mid], row: Math.round(SPR_H * 0.12) };

  // GOLD, not "bright". Two narrower tests were tried and both found the wrong thing:
  // the brightest pixel in the top of the cell is a specular highlight on his pauldron,
  // and the top of the INK is the tip of his sword in every pose where he raises it.
  // The crown is the one gold thing on his head, and gold is a hue, so ask for a hue.
  const gold = (col) => {
    const n = parseInt(col.slice(1), 16);
    const r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn;
    if (mx < 110 || !d) return false;
    let h = 0;
    if (mx === r) h = 60 * (((g - b) / d) % 6);
    else if (mx === g) h = 60 * ((b - r) / d + 2);
    else h = 60 * ((r - g) / d + 4);
    if (h < 0) h += 360;
    return h >= 28 && h <= 58 && d / mx > 0.35;
  };

  // Every gold pixel, and the topmost row that has a real run of them -- his belt, the
  // cross on his tabard and the rim of his shield are gold too, and all of them are
  // below his head in every drawing.
  const rows = [];
  for (let y = 0; y < SPR_H; y++) {
    const xs = [];
    for (let x = 0; x < SPR_W; x++) if (grid[y][x] && gold(grid[y][x])) xs.push(x);
    rows.push(xs);
  }
  let row = -1;
  for (let y = 0; y < SPR_H; y++) {
    if (rows[y].length >= 3) { row = y; break; }
  }
  if (row < 0) {
    // No gold at all -- the parts frames, mostly. Put it on the ink's own centre.
    let top = -1, l = SPR_W, r2 = -1;
    for (let y = 0; y < SPR_H && top < 0; y++) {
      for (let x = 0; x < SPR_W; x++) if (grid[y][x]) { top = y; break; }
    }
    for (let x = 0; x < SPR_W; x++) {
      for (let y = 0; y < SPR_H; y++) if (grid[y][x]) { if (x < l) l = x; if (x > r2) r2 = x; break; }
    }
    return { cols: [Math.round((l + r2) / 2)], row: Math.max(0, top) + 3 };
  }

  // THE ROW THE COLUMNS COME FROM IS THE ROW REPORTED. They were taken from a twelve-row
  // band and reported two rows lower, which is fine on a crown drawn square on and wrong
  // on every pose where it is tilted: on run2 and land the reported row had no ink within
  // three pixels of the reported column, so the glint sat beside his head rather than on
  // it. The densest gold row in the band is the band itself.
  let bestRow = row, bestN = 0;
  for (let y = row; y < Math.min(SPR_H, row + 12); y++) {
    if (rows[y].length > bestN) { bestN = rows[y].length; bestRow = y; }
  }
  row = bestRow;
  const cols = [];
  for (let y = Math.max(0, row - 1); y <= Math.min(SPR_H - 1, row + 1); y++) cols.push(...rows[y]);
  cols.sort((a, b) => a - b);
  const gems = [];
  let run = [cols[0]];
  const flush = () => gems.push(Math.round(run.reduce((t, v) => t + v, 0) / run.length));
  for (let i = 1; i < cols.length; i++) {
    if (cols[i] - cols[i - 1] <= 4) run.push(cols[i]);
    else { flush(); run = [cols[i]]; }
  }
  flush();
  return { cols: gems.length ? gems : [mid], row };
}

export const CROWN_GEMS = Object.fromEntries(NAMES.map((n) => [n, gemsFor(n)]));

// --- the speed afterimage ---------------------------------------------------------
//
// Flat silhouettes of him, one tone per atlas, which the renderer lays down behind him
// on the path he has just taken (see afterimage.js). Baked at load -- a lazily-built
// atlas is a canvas allocation and a full rasterisation inside a frame, which is the
// mistake the font made once already.
//
// THE TWO EFFECTS BEFORE THIS ONE CAME APART FROM HIM IN DIFFERENT WAYS.
//
// The first silhouette trail drew four copies of the CURRENT frame 9 ms apart along -v,
// clamped at 6 and 7 units a copy: on a launch they hung 28 units -- his height -- under
// his boots, a straight line where his path curves. Each copy's cell bottom sat on his
// feet where drawSprite lowers the cell by FOOT_DROP, and no copy took the landing squash
// or the tuck's spin, so even the nearest was a different shape from him. The user saw it
// trailing far behind him, where it should have been on top of him.
//
// It was replaced by a halo: rings of light round his outline, placed by the code that
// places the sprite. That fixed the placement and lost the look, and the roll broke it.
// The tuck turned in quarter turns about the CELL's centre, twelve units above the ball
// of him, so every 71 ms the ball jumped 14 to 21 units (57 to 86 px at zoom 1, measured
// frame by frame at 160 Hz) sideways to his travel. The halo was drawn only where he IS,
// its three copies all in his current rotation and lagged 1.5 units at most along -v, so
// at each quarter turn the lit outline jumped with the ball and nothing was left where he
// had been, and its "trailing" side pointed up to 153 degrees away from where the ball had
// actually come from (over 70 at three of six turns measured) -- the new rotation drawn at
// places he never was in it.
//
// So: the old silhouettes, in the old tone and alphas, each drawn with the state he was
// drawn in at that moment of his path -- pose, facing, squash and quarter turn -- through
// placeCell, the code that places the sprite. And the tuck turns about the ball of him
// now (SPIN_PIVOT): with the old pivot those faithful copies stood a ball's width off him
// for two or three frames after every quarter turn.
//
// From the rows the DRAWING atlas holds (atlasRows), not the whole grid: a standing pose's
// shield point under the landing line is left out of the sprite, so it is left out of the
// silhouette too, and a copy is exactly the shape he is drawn as.
const ghosts = {};

function buildGhost(flip, colour) {
  const grids = flip ? FRAMES_LEFT : FRAMES;
  // Whole numbers (newCanvas), so the headless canvas keeps its size as an integer (a heap
  // double there slows every frame of the process; a browser truncates it anyway).
  const { c, g } = newCanvas(NAMES.length * SPR_W, SPR_H);
  g.fillStyle = colour;
  NAMES.forEach((name, i) => {
    const buf = grids[name];
    const rows = atlasRows(name);
    for (let y = 0; y < rows; y++) {
      let x = 0;
      while (x < SPR_W) {
        if (!buf[y][x]) { x++; continue; }
        let run = 1;
        while (x + run < SPR_W && buf[y][x + run]) run++;
        g.fillRect(i * SPR_W + x, y, run, 1);
        x += run;
      }
    }
  });
  return c;
}

export function ghostAtlas(flip, light) {
  const key = (flip ? 'f' : 'n') + (light ? 'l' : 'd');
  if (!ghosts[key]) ghosts[key] = buildGhost(flip, light ? '#ffffff' : '#000000');
  return ghosts[key];
}

/** Build every silhouette up front, so none is ever allocated inside a frame. */
export function warmGhosts() {
  for (const f of [false, true]) for (const l of [false, true]) ghostAtlas(f, l);
  return 4;
}

/**
 * A flat silhouette of `frame`, placed exactly as drawSprite places the frame for the
 * same arguments. `light` is white for a dark backdrop, black for a light one.
 */
export function drawGhost(ctx, frame, cx, by0, flip = false, spin = 0, sq = 0, light = true) {
  const i = INDEX.get(frame);
  if (i === undefined) return;
  if (FRONT_FRAMES.has(frame)) flip = false;
  placeCell(ctx, ghostAtlas(flip, light), i * SPR_W, frame, cx, by0, spin, sq, flip);
}

/**
 * Draw a frame centred horizontally on `cx`, with its feet on `by`.
 *
 * `cx`/`by` and the destination size are WORLD units; the source rect is the atlas in
 * PIXELS. SPR is BODY * PX, so at zoom 1 this is an exact 1:1 blit and at zoom 2 an
 * exact 2x magnification, both pixel-perfect. The non-integer zooms between them are
 * the only place he is ever resampled.
 *
 * The left-facing atlas is a MIRROR of the right-facing one. This sheet has one facing,
 * unlike the first, so his sword and shield swap hands when he turns around. That is the
 * ordinary compromise for a side-scroller and reads fine in motion; the alternative is a
 * second, left-facing drawing of every side-on pose.
 */
export function drawSprite(ctx, frame, cx, by0, flip = false, spin = 0, sq = 0) {
  const i = INDEX.get(frame);
  if (i === undefined) return;
  if (FRONT_FRAMES.has(frame)) flip = false;
  placeCell(ctx, spriteAtlas(flip), i * SPR_W, frame, cx, by0, spin, sq, flip);
}

/**
 * The point a somersault turns about: the middle of the ball he curls into, in art pixels
 * from the cell's centre (x right, y down), per facing.
 *
 * The tuck used to turn about the middle of its CELL. The cell is 63 x 53 units, sized
 * for a sword arm and a shield, and the ball of him sits in the bottom of it, twelve and a
 * half units under that point -- so each quarter turn swung the ball round a circle
 * twenty-five units across: 17.5 units at every turn, 14 times a second, and on the half
 * turn twenty-five units above his feet. The roll read as a man jittering
 * about the screen, not turning over; anything laid on him (the halo, then the
 * afterimage's copies from before a turn) showed the hop as a second ball beside him.
 * Turned about the ball's own middle he rolls in place, over his feet.
 *
 * Rounded DOWN to a whole art pixel, so the turned drawing still lands on the art-pixel
 * grid (the pivot is on the same grid as the cell's centre was), and so the half turn
 * sits one art pixel above his soles rather than one below. Only the somersault: the
 * death's tumble turns the fall pose, which fills its cell, about the cell's centre.
 */
function spinPivot(grid) {
  let x0 = SPR_W, y0 = SPR_H, x1 = -1, y1 = -1;
  for (let y = 0; y < SPR_H; y++) {
    for (let x = 0; x < SPR_W; x++) {
      if (!grid[y][x]) continue;
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  }
  return [Math.floor((x0 + x1 + 1) / 2 - SPR_W / 2), Math.floor((y0 + y1 + 1) / 2 - SPR_H / 2)];
}
const SPIN_POSES = ['tuck'];
export const SPIN_PIVOT = {
  right: Object.fromEntries(SPIN_POSES.map((n) => [n, spinPivot(FRAMES[n])])),
  left: Object.fromEntries(SPIN_POSES.map((n) => [n, spinPivot(FRAMES_LEFT[n])])),
};

/**
 * Where a pose's cell goes on screen, for the sprite and for anything that must take his
 * exact shape (the afterimage's silhouettes): one function, so the two cannot drift apart
 * the way the first silhouette trail did from him. `img` is any atlas laid out like the
 * sprite's, one SPR_W x SPR_H cell a pose.
 */
export function placeCell(ctx, img, sx, frame, cx, by0, spin, sq, flip) {
  // Stand him on his boots, not on his shield's point or a sword tip. See FOOT_DROP.
  const by = by0 + (FOOT_DROP[frame] || 0);

  if (spin) {
    // Quarter turns only. Rotating pixel art by an arbitrary angle resamples it and
    // turns the outline to mush.
    const q = ((Math.round(spin) % 4) + 4) % 4;
    if (q) {
      // A somersault turns about the ball of him, anything else about the cell's centre
      // (both offsets 0, every argument as it always was). See SPIN_PIVOT.
      const pv = (flip ? SPIN_PIVOT.left : SPIN_PIVOT.right)[frame];
      const ox = pv ? pv[0] / PX : 0, oy = pv ? pv[1] / PX : 0;
      ctx.save();
      ctx.translate(cx + ox, by - BODY_H / 2 + oy);
      ctx.rotate((q * Math.PI) / 2);
      ctx.drawImage(img, sx, 0, SPR_W, SPR_H, -BODY_W / 2 - ox, -BODY_H / 2 - oy, BODY_W, BODY_H);
      ctx.restore();
      return;
    }
  }

  // Squash and stretch preserves volume and keeps the feet planted.
  //
  // Planted means the BOOTS, and the rows under them squash with the rest of the drawing.
  // Lowered by the unsquashed drop, a standing pose landed drop x (1 - ky) too low: in the
  // tail of a landing squash -- the idle or the stride that follows the 0.12 s landing
  // pose, still at a quarter squash -- that put his soles a screen pixel into the ledge
  // at 1.25, 1.5 and 1.75. Only for poses that stand on something; an airborne pose's
  // drop is not a foot, and it stays where it was.
  const kx = 1 + sq * -0.22, ky = 1 + sq * 0.26;
  const w = BODY_W * kx, h = BODY_H * ky;
  const bs = GROUND_POSES.has(frame) ? by0 + (FOOT_DROP[frame] || 0) * ky : by;
  // A standing pose has nothing under its boot row in the atlas (atlasRows), so standing,
  // nothing of him is drawn below the landing line.
  ctx.drawImage(img, sx, 0, SPR_W, SPR_H, cx - w / 2, bs - h, w, h);
}

export function resetSpriteCache() {
  atlas = null;
  atlasFlip = null;
  for (const k of Object.keys(ghosts)) delete ghosts[k];
}
