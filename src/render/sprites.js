/**
 * The last row of a pose that goes into the drawing atlas: for a pose he STANDS in, the
 * row his boots end on, and nothing under it.
 *
 * Once his boots were put on the landing line (bootDrop), what the drop left under the
 * line was the point of his heater shield, held low beside him in every idle -- two or
 * three art rows and the black shadow under them, drawn IN FRONT of the ledge's lit top
 * rows, since he is drawn after the ledges. On a flat deck (DOWNTOWN's gallery, STORM's
 * cloud, the ground) the V of the shield notched the one line a player tracks, right
 * beside his feet. Left out of the atlas, the point ends on the deck, as if resting on it
 * behind the ledge's front edge.
 *
 * Cut here rather than by a clip or a shorter source rect in drawSprite, so the draw call
 * is the one it was: at the zooms between 2 and 1 a changed rect or box moves which art
 * row a screen pixel samples, all the way up his body. This way every pixel above the
 * line is exactly what it was, and under it the rows are simply empty.
 *
 * Only the standing poses, which drawSprite draws only standing, boots on the line: the
 * strides and the landing end on their bottom row and lose nothing; airborne, dying and
 * scene poses keep every row, and FRAMES, the grids tools and tests read, keep the point.
 */
function atlasRows(name) {
  return GROUND_POSES.has(name) ? SPR_H - Math.round((FOOT_DROP[name] || 0) * PX) : SPR_H;
}

function rasterise(grids) {
  const { c, g } = newCanvas(NAMES.length * SPR_W, SPR_H);
  NAMES.forEach((name, i) => {
    const buf = grids[name];
    const rows = atlasRows(name);
    for (let y = 0; y < rows; y++) {
      let x = 0;
      while (x < SPR_W) {
        const col = buf[y][x];
        if (!col) { x++; continue; }
        let run = 1;
        while (x + run < SPR_W && buf[y][x + run] === col) run++;
        g.fillStyle = col;
        g.fillRect(i * SPR_W + x, y, run, 1);
        x += run;
      }
    }
  });
  return c;
}

