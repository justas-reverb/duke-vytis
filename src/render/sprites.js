/**
 * How far each pose must be LOWERED so it stands on its feet rather than on whatever
 * happens to be its lowest pixel.
 *
 * Every pose is positioned by the bottom of its cell, and the importer bottom-aligns
 * each frame on its own lowest ink. For a standing pose that is the boots and it is
 * right. For a running pose it is the TIP OF HIS SWORD, which in this sheet points down
 * and back past his heel -- so the sprite hung from the sword tip and his boots floated.
 * Measured: run1 and fall hovered 1.25 world units, ten screen pixels at the closest
 * zoom. That is the float the user reported, the Duke still off the ground.
 *
 * A foot row is the lowest row with a real FOOTPRINT rather than a dangling point. The
 * ink tapers smoothly down a blade, so there is no sharp edge to find; eight pixels --
 * about 6.5% of the sprite's width -- is the line between a boot and a sword tip, and it
 * is checked by eye with tools/shot-stand.mjs rather than asserted on faith.
 *
 * Anything below the foot row still draws. A sword tip now overlaps the platform edge,
 * which is what a sword hanging past your heel does.
 *
 * That was one sheet ago. The poses he STANDS in are anchored on their boots now, by
 * bootDrop below, because on this sheet FOOT_INK stands him on his shield; the rest --
 * in the air, or lying in a heap -- still use it.
 */
const FOOT_INK = 8;

/**
 * The largest connected piece of a drawing: HIM, rather than what is lying beside him.
 *
 * Some cells are a scene. The knockout is a body, a dropped shield and a fallen crown,
 * drawn at three different depths, so their lowest pixels are eighteen art pixels apart.
 * Anchoring on the whole cell anchored on the SHIELD, whose point dips lowest, and left
 * his body four and a half world units in the air -- lying flat, on nothing.
 *
 * For every ordinary pose the largest piece is him with his sword and shield in it, so
 * this changes nothing there and FOOT_INK still keeps the anchor off the blade.
 */
function largestPiece(grid) {
  const seen = grid.map((r) => r.map(() => false));
  let best = null, bestN = 0;
  for (let y = 0; y < SPR_H; y++) {
    for (let x = 0; x < SPR_W; x++) {
      if (!grid[y][x] || seen[y][x]) continue;
      const stack = [[x, y]];
      seen[y][x] = true;
      const cells = [];
      while (stack.length) {
        const [cx, cy] = stack.pop();
        cells.push([cx, cy]);
        for (let dy = -1; dy <= 1; dy++) {
          for (let dx = -1; dx <= 1; dx++) {
            const nx = cx + dx, ny = cy + dy;
            if (nx < 0 || ny < 0 || nx >= SPR_W || ny >= SPR_H) continue;
            if (!grid[ny][nx] || seen[ny][nx]) continue;
            seen[ny][nx] = true;
            stack.push([nx, ny]);
          }
        }
      }
      if (cells.length > bestN) { bestN = cells.length; best = cells; }
    }
  }
  return best || [];
}

/**
 * Poses that are a SCENE on the ground rather than a figure: him already down, with his
 * gear scattered around him.
 *
 * Only these measure their anchor from the largest piece. Every other pose measures the
 * whole cell, and must: the death plunge also has loose gear in it, but he is in the AIR
 * there, so re-anchoring on his body alone would drop him ten world units the instant the
 * pose changes. There is no ground under a falling man to put him on.
 */
const SCENE_POSES = new Set(['dazed', 'splat']);

function footDrop(grid, scene) {
  const ink = new Int32Array(SPR_H);
  if (scene) {
    // Counted over the largest piece only, so a dropped shield cannot decide where he
    // lies. His body bottoms out eighteen art pixels above the shield's point, and
    // anchoring on the cell left him lying flat four and a half world units in the air.
    for (const [, y] of largestPiece(grid)) ink[y]++;
  } else {
    for (let y = 0; y < SPR_H; y++) {
      for (let x = 0; x < SPR_W; x++) if (grid[y][x]) ink[y]++;
    }
  }
  for (let y = SPR_H - 1; y >= 0; y--) {
    if (ink[y] >= FOOT_INK) return (SPR_H - 1 - y) / PX;
  }
  return 0;
}

/**
 * The poses drawn STANDING ON A LEDGE: every pose frameFor picks while he is grounded,
 * and the run the title screen puts on its bar. These are anchored on their BOOTS.
 *
 * FOOT_INK was right for the sheet it was measured on and wrong for every sheet since.
 * Three imports later nothing hangs past his heel, and what reaches the bottom of the
 * standing cells is the POINT OF HIS SHIELD: he holds the heater low beside him, and it
 * is as blunt as a boot at the bottom -- nine pixels on its last row in idle0, so FOOT_INK
 * took it for a footprint and stood him on it. In the other four idles it skipped the
 * point's last row, one to six pixels wide, and stood him on its second. Either way the
 * boots hung one or two art pixels over the ledge, up to half a world unit, and the idle
 * is where he stands still: two screen pixels of sky under his soles at zoom 1, four at
 * zoom 2, on every ledge. The grass on the old ledges hid it; a flat timber deck did not.
 * And the same threshold cut the other way on the run: run1's and run2's toes end in a
 * six- and a four-pixel row, which it skipped, so the toe sank a pixel into the ledge.
 *
 * So these ask what the lowest pixel IS rather than how wide it is. Airborne poses keep
 * FOOT_INK -- there is no ledge under him to measure against, the fall's anchor is where
 * the splat throws his pieces from (posePoint), and nothing about them was reported.
 */
const GROUND_POSES = new Set([...IDLE_CYCLE, ...RUN_CYCLE, 'land']);

// A pixel under this brightness (tone value, 0-255) is outline or cast shadow. Both the
// shield and the boots are ringed in near-black, and the shield's point sits on a black
// shadow of its own, so a dark pixel says nothing about which one it belongs to.
const FOOT_LIT = 70;
// How far up a column (art pixels) the colours get a vote. Far enough to get past a
// boot's sole -- up to four rows of black under a toe -- and into the plate above it.
const FOOT_REACH = 10;

/**
 * How far a GROUNDED pose must be lowered to stand on its boots: the lowest row of ink
 * that is not the shield.
 *
 * Found by colour, per column of the drawing's bottom edge. The lit pixels in the few
 * rows above a column's lowest ink vote: the shield's rim and field are GOLD and CRIMSON,
 * his sabatons are STEEL, and the browns both share abstain. A column dark all the way
 * up -- the shadow under the shield's point, a thick sole -- goes with the nearest
 * column it is joined to along the bottom that did get a verdict. The boots' lowest row
 * then sits on the ledge. The shield's point below it used to hang over the ledge's lip
 * in front of it, across the ledge's lit top rows; the atlas now leaves out a standing
 * pose's rows under its boots (atlasRows), so the point ends on the deck.
 *
 * Measured on this sheet by eye, before this was written, and it agrees on all nine:
 * boots end on row 209 in idle0 and idle2, 208 in idle1, idle3 and idle4, and on the last
 * row, 211, in the three strides and the landing -- where a toe is the lowest thing.
 * test-sprites holds the rule to those rows, so a re-import that moves his feet fails
 * there and gets looked at, instead of drifting the way FOOT_INK did.
 *
 * It would take a blade hanging below the heel for a boot, as the sheet before this one
 * had: steel is steel. Should that come back, the test fails first.
 */
function bootDrop(grid) {
  const low = new Int32Array(SPR_W).fill(-1);
  const vote = new Int8Array(SPR_W);        // +1 boot, -1 shield, 0 no verdict
  for (let x = 0; x < SPR_W; x++) {
    let y = SPR_H - 1;
    while (y >= 0 && !grid[y][x]) y--;
    if (y < 0) continue;
    low[x] = y;
    let steel = 0, arms = 0;
    for (let yy = y; yy >= Math.max(0, y - FOOT_REACH); yy--) {
      const c = grid[yy][x];
      if (!c || tone(c).v < FOOT_LIT) continue;
      if (ROLE_TEST.gold(c) || ROLE_TEST.red(c)) arms++;
      else if (ROLE_TEST.steel(c)) steel++;
    }
    vote[x] = Math.sign(steel - arms);
  }
  // The undecided take the nearest verdict they are joined to: walk out both ways across
  // columns that all have ink, and stop at the first gap in the silhouette. A piece with
  // no verdict anywhere in it -- a detached fleck of shadow -- decides nothing.
  const side = (x, dir) => {
    for (let d = 1, xx = x + dir; xx >= 0 && xx < SPR_W && low[xx] >= 0; d++, xx += dir) {
      if (vote[xx]) return { d, v: vote[xx] };
    }
    return null;
  };
  let row = -1;
  for (let x = 0; x < SPR_W; x++) {
    if (low[x] < 0) continue;
    let v = vote[x];
    if (!v) {
      const l = side(x, -1), r = side(x, 1);
      v = !l ? (r ? r.v : 0) : !r ? l.v : (l.d <= r.d ? l.v : r.v);
    }
    if (v > 0 && low[x] > row) row = low[x];
  }
  return row < 0 ? footDrop(grid, false) : (SPR_H - 1 - row) / PX;
}

export const FOOT_DROP = Object.fromEntries(NAMES.map((n) => [n,
  GROUND_POSES.has(n) ? bootDrop(FRAMES[n]) : footDrop(FRAMES[n], SCENE_POSES.has(n))]));

/**
 * The individual BITS he comes apart into, found in the two `parts` drawings.
 *
 * Those two cells are a parts bin, not a pose: a torso, a head, arms, legs, his sword
 * and his shield, arranged to fit the cell rather than to stand in it. Drawn whole and
 * bottom-aligned like any other frame, the arms end up seventy pixels in the air.
 *
 * So each connected piece is found and exposed on its own, and the renderer scatters
 * them along the floor. Ordered biggest first, so the torso lands before the fingers
 * and the small pieces settle on top.
 *
 * Each bit keeps its own CELLS, not just its box. The torso's box and the arm drawn
 * hanging beside it overlap by eleven columns, and a bit copied out of its box used to
 * carry a slice of its neighbour with it.
 */
function splitBits(name) {
  const grid = FRAMES[name];
  if (!grid) return [];
  return components(grid)
    .filter((c) => c.n >= MIN_PIECE)
    .map((c) => ({ frame: name, grid, cells: c.cells, n: c.n,
      sx: c.x0, sy: c.y0, sw: c.x1 - c.x0 + 1, sh: c.y1 - c.y0 + 1 }));
}

/**
 * What each bit IS, so it can start the burst where that part of him was.
 *
 * The two bins are laid out as the upper body and the lower: a head, a torso and arms
 * in one, legs, the sword and the shield in the other. Inside a bin the roles are told
 * apart by colour -- the tabard is the bluest thing he wears, his hair and beard the
 * warmest, the shield's field the reddest -- and the sword is the sparsest piece, a thin
 * blade in a big box. Asked by hue and by rank, never by coordinate or palette letter,
 * so a re-import that moves every piece still sorts them.
 */
function assignRoles(bits) {
  // A plate cut off the torso (cutLimbs) is what it was cut as: asked by colour it would
  // rank as an arm, and take an arm's slot at the burst.
  const upper = bits.filter((b) => b.frame === 'parts0' && b.role !== 'plate');
  const lower = bits.filter((b) => b.frame === 'parts1' && b.role !== 'plate');
  const best = (list, score) => list.reduce((a, b) => (!a || score(b) > score(a) ? b : a), null);
  const share = (b, test) => shareOf(b.grid, b.cells, test);
  const torso = best(upper, (b) => share(b, ROLE_TEST.blue));
  const head = best(upper.filter((b) => b !== torso), (b) => share(b, ROLE_TEST.warm));
  const shield = best(lower, (b) => share(b, ROLE_TEST.red));
  const sword = best(lower.filter((b) => b !== shield), (b) => -b.n / (b.sw * b.sh));
  for (const b of upper) b.role = b === torso ? 'torso' : b === head ? 'head' : 'arm';
  for (const b of lower) b.role = b === shield ? 'shield' : b === sword ? 'sword' : 'leg';
  return bits;
}

/**
 * An arm the artist left ON the torso, cut off it.
 *
 * The parts bin is meant to hold one piece per part, and on this import it does not:
 * three arms are drawn loose, and the fourth -- pauldron, vambrace and gauntlet -- hangs
 * from the torso's shoulder, touching the tabard all down its armhole. Being one
 * connected piece, it flew as the torso: a tabard with an arm dangling off it while the
 * other three arms flew free. The import before drew it loose (eleven pieces, then ten).
 *
 * The cut is read from the drawing, never from a coordinate, so a re-import still works:
 *  - the torso is its TABARD, the biggest patch of blue in the piece;
 *  - what hangs off it is measured by how far each pixel is from the tabard, walking
 *    inside the piece;
 *  - the cut is the cheapest line of pixels separating the tabard from the far end of
 *    what hangs off it, where outline ink costs 1 and lit ink up to 9 (a minimum vertex
 *    cut, cutAt). Two drawn parts meet along an outline, so that is where it runs: here
 *    down the tabard's armhole, 41 pixels, every one of them outline;
 *  - and it is an ARM only if it takes as much ink as the arms he drew loose
 *    (LIMB_MATCH). Where the far end is taken to start decides where the cheapest line
 *    lies -- from the gauntlet alone it is the wrist, from the forearm the elbow -- so the
 *    far end is tried from 30% of the way out to 90%, and the cut kept is the one whose
 *    piece is nearest an arm. Here that is the whole arm, pauldron and all: 1579 px
 *    against loose arms of 1503-1545 (the median, 1511, is the measure), where starting
 *    the far end at 60% cuts at the elbow and takes 853.
 *
 * The cut line goes to BOTH pieces: it is the outline each of them has where the other
 * one was, as the art's own pieces have one all round. A pixel of it that is not outline
 * ink (none on this sheet) is painted in the piece's commonest outline colour. Then it
 * looks again for a second arm, until what it would cut off is not an arm: the torso's
 * own right pauldron, the farthest thing left on it (378 px, -75%). That comes off last, as
 * a PLATE: the cut is kept if it takes at least PLATE_MIN of an arm and is mostly steel
 * (PLATE_STEEL), so the tabard does not lie wearing a steel shoulder.
 *
 * Each piece cut off keeps where it HUNG (`hang`): its box's centre from the torso's, in art
 * pixels. The burst starts it there, beside wherever the torso starts, so at the instant
 * he comes apart the two are the drawing they were cut from and the arm comes off the
 * shoulder it was drawn on -- rather than from a slot for loose arms, which is somewhere
 * else on him.
 */
function cutLimbs(bits) {
  const torso = bits.find((b) => b.role === 'torso');
  const arms = bits.filter((b) => b.role === 'arm').map((b) => b.n).sort((a, b) => a - b);
  // No loose arm, no measure of one: nothing is cut rather than something guessed at.
  if (!torso || !arms.length) return bits;
  const ref = arms[arms.length >> 1];
  const out = bits.filter((b) => b !== torso);
  const limbs = [];
  let body = torso;
  for (let k = 0; k < 4; k++) {
    const cut = cutLimb(body, ref);
    if (!cut) break;
    limbs.push(cut.limb);
    body = cut.body;
  }
  // Then the torso's own right pauldron. The loop above stops at the first cut too small to
  // be an arm, and that was it: a plate of steel on the torso's shoulder, 378 px, a quarter
  // of an arm. Left on, it flew and lay as a stump -- the user, of the build with the fused
  // arm already cut free, still saw an arm that did not come off properly at the death, and in
  // the settled pieces the tabard still wore a steel shoulder. It comes off as a piece of its
  // own now (PLATE_MIN, cutLimb's 'plate' mode), and starts where it hung, like a cut arm.
  const plate = cutLimb(body, ref, 'plate');
  if (plate) { limbs.push(plate.limb); body = plate.body; }
  // From the torso as it is finally drawn, after every cut: that is the box the burst
  // centres on the torso's anchor.
  for (const limb of limbs) {
    limb.hang = { dx: limb.sx + limb.sw / 2 - (body.sx + body.sw / 2),
      dy: limb.sy + limb.sh / 2 - (body.sy + body.sh / 2) };
  }
  return out.concat(limbs, [body]);
}

// The far end of what hangs off the tabard is tried from this share of the way out.
const LIMB_SEEDS = [0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9];

/**
 * One arm cut off `piece`, or null if nothing hanging off its tabard is arm-sized. In 'plate'
 * mode, the plate of armour left hanging off it instead: smaller than an arm (under
 * 1 - LIMB_MATCH of one) but at least PLATE_MIN of one, and at least PLATE_STEEL steel.
 */
function cutLimb(piece, ref, mode = 'arm') {
  const W = SPR_W, grid = piece.grid, cells = piece.cells, n = cells.length;
  const at = new Int32Array(SPR_W * SPR_H).fill(-1);
  const px = new Int32Array(n), py = new Int32Array(n);
  cells.forEach(([x, y], k) => { at[y * W + x] = k; px[k] = x; py[k] = y; });
  // Each pixel's 8 neighbours inside the piece, as one flat list: pixel k's are
  // nbList[nbAt[k] .. nbAt[k + 1]). Flat, because the flow below walks them thousands of
  // times and an array per pixel was most of what it cost to load.
  const nbAt = new Int32Array(n + 1), nbList = new Int32Array(8 * n);
  for (let k = 0, m = 0; k < n; k++) {
    nbAt[k] = m;
    for (let dy = -1; dy <= 1; dy++) {
      for (let dx = -1; dx <= 1; dx++) {
        const nx = px[k] + dx, ny = py[k] + dy;
        if ((dx || dy) && nx >= 0 && ny >= 0 && nx < SPR_W && ny < SPR_H && at[ny * W + nx] >= 0) nbList[m++] = at[ny * W + nx];
      }
    }
    nbAt[k + 1] = m;
  }
  // The palette is a few dozen colours: read each one's tone once.
  const vOf = new Map();
  const value = (c) => { let v = vOf.get(c); if (v === undefined) vOf.set(c, v = tone(c).v); return v; };

  // The tabard: the largest 4-connected patch of blue. 4-connected, because the steel
  // has blue glints in it that touch the tabard only at a corner.
  const blue = cells.map(([x, y]) => ROLE_TEST.blue(grid[y][x]));
  let tabard = [];
  {
    const seen = new Uint8Array(n);
    for (let s = 0; s < n; s++) {
      if (!blue[s] || seen[s]) continue;
      const patch = [s];
      seen[s] = 1;
      for (let h = 0; h < patch.length; h++) {
        const k = patch[h];
        for (let m = nbAt[k]; m < nbAt[k + 1]; m++) {
          const j = nbList[m];
          if (blue[j] && !seen[j] && (px[j] === px[k] || py[j] === py[k])) { seen[j] = 1; patch.push(j); }
        }
      }
      if (patch.length > tabard.length) tabard = patch;
    }
  }
  if (tabard.length < MIN_PIECE) return null;

  // How far out from the tabard each pixel is, walking inside the piece.
  const reach = new Int32Array(n).fill(-1);
  const queue = tabard.slice();
  for (const k of queue) reach[k] = 0;
  for (let h = 0; h < queue.length; h++) {
    const k = queue[h];
    for (let m = nbAt[k]; m < nbAt[k + 1]; m++) {
      const j = nbList[m];
      if (reach[j] < 0) { reach[j] = reach[k] + 1; queue.push(j); }
    }
  }
  let far = 0, tip = -1;
  for (let k = 0; k < n; k++) if (reach[k] > far) { far = reach[k]; tip = k; }
  if (!far) return null;

  const cost = cells.map(([x, y]) => {
    const v = value(grid[y][x]);
    return v < CUT_OUTLINE_V ? 1 : 1 + Math.round(v / 32);
  });
  const cutAt = minCut(n, nbAt, nbList, cost, tabard);
  let best = null;
  for (const share of LIMB_SEEDS) {
    // The far end is the pixels at least `share` of the way out that are joined to the
    // farthest one through pixels as far out: the end of ONE thing hanging off the tabard.
    // It was every pixel that far out, and at 30% and 40% that took in ends of the torso's
    // own right side as well (flecks of 54 and 6 px, then 4), so the cut went round them
    // too and they would have flown off with the arm as specks of their own. On this sheet
    // 50% won by 0.3% of an arm (1579 px against 1583, fleck and all); with the armhole
    // painted over in lit steel, 40% won and the fleck flew. Now 30-50% all make the same
    // clean cut.
    const sink = [tip];
    const inSink = new Uint8Array(n);
    inSink[tip] = 1;
    for (let h = 0; h < sink.length; h++) {
      const k = sink[h];
      for (let m = nbAt[k]; m < nbAt[k + 1]; m++) {
        const j = nbList[m];
        if (!inSink[j] && reach[j] >= share * far) { inSink[j] = 1; sink.push(j); }
      }
    }
    const line = cutAt(sink);
    if (!line) continue;
    // Which side of the line each pixel is on: joined to the tabard without crossing it,
    // or not.
    const side = new Uint8Array(n);           // 0 limb, 1 body, 2 the line itself
    for (const k of line) side[k] = 2;
    const walk = tabard.filter((k) => side[k] !== 2);
    for (const k of walk) side[k] = 1;
    for (let h = 0; h < walk.length; h++) {
      const k = walk[h];
      for (let m = nbAt[k]; m < nbAt[k + 1]; m++) if (!side[nbList[m]]) { side[nbList[m]] = 1; walk.push(nbList[m]); }
    }
    let limbInk = line.length;
    for (let k = 0; k < n; k++) if (!side[k]) limbInk++;
    const size = limbInk / ref;
    if (mode === 'arm') {
      const miss = Math.abs(size - 1);
      if (miss <= LIMB_MATCH && (!best || miss < best.miss)) best = { miss, side };
      // A far end that starts further out lies inside the last one, and so does its cut:
      // once a cut takes too little to be an arm, every later one does too.
      if (limbInk < ref * (1 - LIMB_MATCH)) break;
    } else {
      // The whole plate, not a sliver of it: of the cuts in range, the one that takes most.
      if (size < PLATE_MIN) break;
      if (size < 1 - LIMB_MATCH) {
        let lit = 0, steel = 0;
        for (let k = 0; k < n; k++) {
          if (side[k]) continue;
          const c = grid[py[k]][px[k]];
          if (value(c) < CUT_OUTLINE_V) continue;
          lit++;
          if (ROLE_TEST.steel(c)) steel++;
        }
        if (lit && steel / lit >= PLATE_STEEL && (!best || size > best.size)) best = { size, side };
      }
    }
  }
  if (!best) return null;

  // The line belongs to both. Where it runs through lit ink rather than an outline,
  // both pieces get the piece's commonest outline colour there instead.
  const tally = {};
  for (const [x, y] of cells) {
    const c = grid[y][x];
    if (value(c) < CUT_OUTLINE_V) tally[c] = (tally[c] || 0) + 1;
  }
  const ink = Object.keys(tally).sort((a, b) => tally[b] - tally[a])[0] || '#000000';
  const g2 = grid.map((r) => r.slice());
  const make = (keep, role) => {
    const own = [];
    let x0 = SPR_W, y0 = SPR_H, x1 = -1, y1 = -1;
    cells.forEach(([x, y], k) => {
      if (!keep(best.side[k])) return;
      own.push([x, y]);
      if (best.side[k] === 2 && value(grid[y][x]) >= CUT_OUTLINE_V) g2[y][x] = ink;
      if (x < x0) x0 = x; if (x > x1) x1 = x;
      if (y < y0) y0 = y; if (y > y1) y1 = y;
    });
    return { frame: piece.frame, grid: g2, cells: own, n: own.length, role,
      sx: x0, sy: y0, sw: x1 - x0 + 1, sh: y1 - y0 + 1 };
  };
  return { body: make((s) => s >= 1, piece.role), limb: make((s) => s !== 1, mode) };
}

/**
 * The cheapest set of pixels whose removal separates `source` from a sink set, as a
 * function of the sink set -- the graph is built once and reused for every sink tried.
 * Each pixel is a node split in two, joined by an edge of its cost; neighbours are
 * joined both ways without limit; the maximum flow's saturated pixel edges are the cut.
 *
 * Dinic's method: one breadth-first pass lays out the level graph, then as many paths as
 * it holds are pushed before the next. One shortest path per pass, which was the first
 * version, was 72 ms of BFS at every load of the game for the forty or so units of flow a
 * cut here carries.
 */
function minCut(n, nbAt, nbList, cost, source) {
  const S = 2 * n, T = 2 * n + 1, N = 2 * n + 2, INF = 1 << 28;
  // in -> out and out -> T for every pixel, out -> in for every neighbour, S -> in for the source
  const edges = 2 * n + nbAt[n] + source.length;
  const to = new Int32Array(2 * edges), next = new Int32Array(2 * edges);
  const base = new Int32Array(2 * edges), head = new Int32Array(N).fill(-1);
  let e = 0;
  const add = (u, v, c) => {
    to[e] = v; base[e] = c; next[e] = head[u]; head[u] = e++;
    to[e] = u; base[e] = 0; next[e] = head[v]; head[v] = e++;
  };
  const isSource = new Uint8Array(n);
  for (const k of source) isSource[k] = 1;
  const pixel = new Int32Array(n), toSink = new Int32Array(n);
  for (let k = 0; k < n; k++) {
    pixel[k] = e;
    add(2 * k, 2 * k + 1, isSource[k] ? INF : cost[k]);
    for (let m = nbAt[k]; m < nbAt[k + 1]; m++) add(2 * k + 1, 2 * nbList[m], INF);
    toSink[k] = e;
    add(2 * k + 1, T, 0);
  }
  for (const k of source) add(S, 2 * k, INF);
  const cap = new Int32Array(2 * edges), level = new Int32Array(N), it = new Int32Array(N);
  const q = new Int32Array(N);
  const layer = () => {
    level.fill(-1);
    level[S] = 0;
    let qh = 0, qt = 0;
    q[qt++] = S;
    while (qh < qt) {
      const u = q[qh++];
      for (let i = head[u]; i >= 0; i = next[i]) {
        if (cap[i] > 0 && level[to[i]] < 0) { level[to[i]] = level[u] + 1; q[qt++] = to[i]; }
      }
    }
    return level[T] >= 0;
  };
  // Paths are a shortest route across a piece, a hundred or so nodes: recursion is fine.
  const push = (u, f) => {
    if (u === T) return f;
    for (; it[u] >= 0; it[u] = next[it[u]]) {
      const i = it[u], v = to[i];
      if (cap[i] > 0 && level[v] === level[u] + 1) {
        const d = push(v, Math.min(f, cap[i]));
        if (d > 0) { cap[i] -= d; cap[i ^ 1] += d; return d; }
      }
    }
    return 0;
  };
  return (sink) => {
    cap.set(base);
    for (const k of sink) {
      if (isSource[k]) return null;
      cap[pixel[k]] = INF;
      cap[toSink[k]] = INF;
    }
    while (layer()) {
      it.set(head);
      for (let f = push(S, INF); f > 0; f = push(S, INF)) {
        if (f >= INF) return null;         // the sink touches the tabard: no cut exists
      }
    }
    // The cut: pixels whose in-half the source still reaches and whose out-half it does
    // not. The last layer() found no path, so `level` marks exactly what it reaches.
    const line = [];
    for (let k = 0; k < n; k++) if (level[2 * k] >= 0 && level[2 * k + 1] < 0) line.push(k);
    return line;
  };
}

