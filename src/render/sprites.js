// DUKE VYTIS - the climber.
//
// A crowned Lithuanian grand duke in full plate: tall gold crown, an enormous forked
// auburn beard, steel harness under a deep blue tabard with a gold cross, a red heater
// shield charged with the Vytis -- the armoured horseman of the Grand Duchy's arms, sword
// raised, on a white horse -- and a longsword. "Vytis" is the old name for the
// arms of Lithuania and it means THE CHASE, which for a game about being chased up a
// tower was too good to pass up.
//
// --- where the art comes from ------------------------------------------------
//
// It is IMPORTED, not authored here. src/render/vytisart.js is generated by
// tools/import-sprite.mjs from the artist's reference sheet, and this file is only the
// engine that poses and draws it.
//
// That replaced a procedural system: hand-written ASCII grids for the head and torso,
// with arms and legs rasterised at bake time from joint angles. The procedure was the
// right answer while the art was mine, because a new pose cost two numbers instead of a
// new drawing. It is the wrong answer now -- the art is drawn by somebody who can draw,
// and the only job here is to get their pixels on screen unaltered.
//
// --- resolution ---------------------------------------------------------------
//
// SPR_W x SPR_H are the sheet's own dimensions and BODY is those divided by PX, so one
// art pixel is exactly one backing-store pixel. That identity is the whole reason he
// looks like the reference rather than a resample of it, and test-sprites.mjs asserts
// it.
//
// The cell is 252x212 art pixels, 63x53 world units, and he stands 177 pixels -- about
// 44 units -- in idle0. That is a decision, not arithmetic: he was 77 pixels and 19.25
// units once, sized to fit the 23-unit gap between floors, and was made this big on
// purpose because he read as too small to be the hero. He draws over the ledge above
// him now. His COLLISION box is a separate 16x22 (PLAYER_W, PLAYER_H), which is why the
// sprite can change size without a single jump changing.
//
// The sheet was not pixel art when it arrived: a high-resolution illustration in a
// pixel-art style, tens of thousands of colours, anti-aliased throughout. The importer
// resamples it and snaps every colour to a 36-entry palette built from the sheet, which
// is what turns a gradient back into an edge. The exact command is in the head of
// vytisart.js; see tools/import-sprite.mjs.

import { SPR_W, SPR_H, PAL, FRAMES as RAW_ART } from './vytisart.js';

