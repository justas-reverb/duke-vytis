// Bring the artist's background tiles into the game.
//
//   node tools/import-backgrounds.mjs                                   report
//   node tools/import-backgrounds.mjs --emit > src/render/bgart.js      write the manifest
//
// The tiles live in assets/backgrounds/ as <ZONE>-far.png, <ZONE>-mid.png and
// <ZONE>-near.png, 256 x 256, any capitalisation (the font on the template sheet only has
// capitals, so a name typed from it may come out all upper case). This does not convert
// or copy anything: the game loads those PNGs as they are. It CHECKS them, and it writes
// src/render/bgart.js, the list of which zone-and-layer tiles exist -- the game only asks
// for what is listed, so a zone with no art never requests a file that is not there (a
// 404 fails the desktop build's smoke test).
//
// What it checks, per tile:
//   SIZE  must be exactly 256 x 256, or it is left out and the painter is used instead.
//   WRAP  the mean difference between the left and right edge columns, and between the top
//         and bottom edge rows, transparency included. Under 10 is seamless, over 30 is a
//         seam on the screen every 128 units. Reported, never fatal: art arrives in stages.
//
// See tools/background-template.mjs for the sheet to draw into.

import fs from 'node:fs';
import path from 'node:path';
import { readPNG } from './pngread.mjs';

const EMIT = process.argv.includes('--emit');
const DIR = 'assets/backgrounds';
const TILE = 256;
const LAYERS = ['far', 'mid', 'near'];
const { THEMES } = await import('../src/game/themes.js');

const files = fs.existsSync(DIR) ? fs.readdirSync(DIR) : [];
const byLower = new Map(files.map((f) => [f.toLowerCase(), f]));
const used = new Set();

function rgba(img, x, y) {
  const i = (y * img.w + x) * img.ch;
  if (img.ch === 4) return [img.data[i], img.data[i + 1], img.data[i + 2], img.data[i + 3]];
  if (img.ch === 3) return [img.data[i], img.data[i + 1], img.data[i + 2], 255];
  return [img.data[i], img.data[i], img.data[i], 255];
}
// Difference between two pixels, alpha-weighted: two fully transparent pixels match
// whatever their colour; transparent against opaque is a full mismatch.
function diff(a, b) {
  const aa = a[3] / 255, ba = b[3] / 255;
  const col = (Math.abs(a[0] * aa - b[0] * ba) + Math.abs(a[1] * aa - b[1] * ba) + Math.abs(a[2] * aa - b[2] * ba)) / 3;
  return Math.max(col, Math.abs(a[3] - b[3]));
}
function wrap(img) {
  let h = 0, v = 0;
  for (let y = 0; y < img.h; y++) h += diff(rgba(img, 0, y), rgba(img, img.w - 1, y));
  for (let x = 0; x < img.w; x++) v += diff(rgba(img, x, 0), rgba(img, x, img.h - 1));
  return [h / img.h, v / img.w];
}

const found = {};
const problems = [];
const rows = [];
for (const th of THEMES) {
  for (const layer of LAYERS) {
    const want = `${th.name}-${layer}.png`.toLowerCase();
    const actual = byLower.get(want);
    if (!actual) continue;
    used.add(actual);
    const rel = `${DIR}/${actual}`;
    let img;
    try { img = readPNG(rel); } catch (e) { problems.push(`${actual}: ${e.message}`); continue; }
    if (img.w !== TILE || img.h !== TILE) {
      problems.push(`${actual}: ${img.w}x${img.h}, must be ${TILE}x${TILE} -- left out, the painter draws this layer`);
      continue;
    }
    const [h, v] = wrap(img);
    (found[th.name] = found[th.name] || {})[layer] = rel;
    found[th.name][`${layer}Wrap`] = [Math.round(h * 10) / 10, Math.round(v * 10) / 10];
    rows.push({ zone: th.name, layer, h, v });
  }
}
const stray = files.filter((f) => !used.has(f) && /\.png$/i.test(f));

if (!EMIT) {
  const verdict = (x) => (x < 10 ? 'seamless' : x < 30 ? 'rough' : 'SEAM');
  console.log(`  ${rows.length} of ${THEMES.length * 3} background tiles found in ${DIR}/`);
  for (const r of rows) {
    console.log(`  ${r.zone.padEnd(10)} ${r.layer.padEnd(5)} left/right ${r.h.toFixed(1).padStart(5)} ${verdict(r.h).padEnd(8)}` +
      `  top/bottom ${r.v.toFixed(1).padStart(5)} ${verdict(r.v)}`);
  }
  for (const p of problems) console.log(`  PROBLEM  ${p}`);
  for (const f of stray) console.log(`  IGNORED  ${f} -- not <ZONE>-far|mid|near.png for any zone`);
  if (!rows.length) console.log('  (none yet -- every layer is painted by src/render/bgpaint/)');
  process.exit(0);
}

const out = [];
out.push('// GENERATED by tools/import-backgrounds.mjs -- do not edit by hand.');
out.push('//');
out.push('//   node tools/import-backgrounds.mjs --emit > src/render/bgart.js');
out.push('//');
out.push("// The artist's background tiles that exist in assets/backgrounds/, by zone and layer.");
out.push("// Anything not listed is painted by the zone's code painter (src/render/bgpaint/).");
out.push('// Listing only what exists is what keeps the game from requesting a missing file.');
out.push('// The *Wrap pairs are [left/right, top/bottom] mean edge differences; under 10 is');
out.push('// seamless, over 30 is a visible seam.');
out.push('');
out.push(`export const BG_TILE = ${TILE};`);
out.push('');
out.push('export const BG_FILES = {');
for (const [zone, e] of Object.entries(found)) {
  out.push(`  ${zone}: {`);
  for (const layer of LAYERS) {
    if (!e[layer]) continue;
    out.push(`    ${layer}: '${e[layer]}',`);
    out.push(`    ${layer}Wrap: [${e[`${layer}Wrap`].join(', ')}],`);
  }
  out.push('  },');
}
out.push('};');
out.push('');
console.log(out.join('\n'));
void path;
